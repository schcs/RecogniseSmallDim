TestBasisSp := function(basH, basK, basT, wH, g)
    F := CoefficientRing(g);
    p := Characteristic(F);
    dimg := Dimension(g);
    dim := SolveAltSquareDimEq(dimg : type := "Sp");
    pdividesd := (dim mod p) eq 0;
    dH := SolveAltSquareDimEq(#basH : type := "Sp");
    dK := SolveAltSquareDimEq(#basK : type := "Sp");

    // Possible combinations for the scalars
    scalars := [<a, b, c, d> : a in [1, -1], b in [1, -1], c in [1], d in [1]];

    // Check all possible combinations of scalars
    for s in scalars do
        // Build the basis
        bas := BuildBasisMatrixSp(F, dH, dK : scalars := s) * Matrix(basH cat basK cat basT cat wH);
        bas_mat := Matrix(bas);

        // Take random element from the group, ensuring it's outside the center
        repeat
            x0 := Random(g);
        until (x0, Random(g)) ne x0^0;

        // Apply basis transform on x0
        x := bas_mat * x0 * bas_mat^-1;

        // Find preimage of x
        y := __funcAltSquareToSLdq(x : type := "Sp");

        // Check if the result is valid
        if Category(y) eq BoolElt then
            continue;
        end if;

        // Find image of y and check if result is valid
        x1 := __funcSLdqToAltSquare(y : type := "Sp");
        if Category(x1) eq BoolElt or not IsInvertible(x1) then
            continue;
        end if;

        // x should be x1 if the scalars are right
        if x eq x1 then
            return true, s;
        end if;
    end for;

    return false, _;
end function;
    
 /* find an involution with sufficiently large minus one eigenspace and 
       its centraliser. */

InvolutionWithCentralizer := function(G, type, dimG, dim)
    // Set eigenspace dimensions using heuristics
    if type eq "Omega-" and dim eq 12 then 
        eiglim1 := 36; eiglim2 := 36;
    elif type eq "Omega" and dim eq 9 then 
        eiglim1 := 18; eiglim2 := 18;
    elif type eq "Sp" and dim eq 6 then 
        eiglim1 := 9; eiglim2 := 9;
    elif type eq "Sp" and dim eq 14 then 
        eiglim1 := 40; eiglim2 := 49;
    elif type eq "Sp" and dim eq 12 then 
        eiglim1 := 32; eiglim2 := 36;
    else 
        eiglim1 := case< dim | 6: 8, 11: 29, 12: 35, default: (2/9)*dim^2 >; 
        //eiglim1 := case< dim | 6: 8, 11: 29, 12: 35, default: (2/9)*dim^2 >;
        eiglim2 := case< dim | 6: 8, default: (1/4)*dim^2 >; 
    end if;

    // Property function for InvolutionWithProperty
    propfunc := function(x)
        dmin := Dimension(Eigenspace(x, -1));
        return dmin ge eiglim1 and dmin le eiglim2;
    end function;

    // Completion checking function
    NrGensCentInv := 10;
    __compcheck := func< G, C, g | NumberOfGenerators(C) ge NrGensCentInv >;

    if type eq "Sp" then
        dl := 3;
        nocomponents := case< dim mod Characteristic(CoefficientRing(G)) eq 0 | true: 3, default: 4 >;
        good_dims := function(dims)
            if #dims ne nocomponents or &+dims ne dimG then 
                return false;
            end if;
            dims1 := [SolveAltSquareDimEq(x : type := "Sp", pmaydividedim := false) : x in dims];
            poszero := [x : x in [1..#dims] | dims1[x] eq 0 and dims[x] ne 1];
            posnonzero := [x : x in [1..#dims] | dims1[x] ne 0 and dims[x] ne 1];
            return &*dims1[posnonzero] eq dims[poszero][1];
        end function;
    else
        dl := case< dim | 8: 2, 9: 2, 10: 2, 11: 2, 12: 2, 18: 2, default : 1 >;
        nocomponents := 3;
        good_dims := func< dims | #dims eq nocomponents and not 1 in dims and &+dims eq dimG >;
    end if;

    repeat
        inv := InvolutionWithProperty(G, propfunc);
        gensC := [];
        gensCD := [];

        repeat
            C := CentraliserOfInvolution(G, inv : CompletionCheck := __compcheck);
            CD := MyDerivedGroupMonteCarlo(C : NumberGenerators := NrGensCentInv, DerivedLength := dl);

            gensC cat:= GeneratorsSequence(C);
            gensCD cat:= GeneratorsSequence(CD);

            C := sub< Universe(gensC) | gensC >;
            CD := sub< Universe(gensCD) | gensCD >;

            M := GModule(CD);
            mins := [x : x in MinimalSubmodules(M : Limit := 4)];
            dim_mins := [Dimension(x) : x in mins];
            nr_ones := #[x : x in [1..#mins] | dim_mins[x] eq 1];
            stop_condition := #mins lt nocomponents + 1 or nr_ones eq 1;
        until stop_condition;
    until good_dims(dim_mins);

    return inv, gensCD, CD, M, mins;
end function;


// a part of the basis calculated in the main function might need to be multiplied by a scalar
// this is done in this function 
find_scalars_for_exterior_square := function( G, bas_mat, dH, dK )

    q := #CoefficientRing( G ); dim := dH + dK;
    p12 := funcpos_altsquare( dim, 1, 2 );
    p13 := funcpos_altsquare( dim, 1, dH+1 );
    p23 := funcpos_altsquare( dim, 2, dH+1 );
    p14 := funcpos_altsquare( dim, 1, dH+2 );
    p34 := funcpos_altsquare( dim, dH+1, dH+2 );

    while true do
        x := bas_mat*Random( G )*bas_mat^-1;
        mat1 := Matrix( GF( q ), 3, 3, [
                        x[p12,p12],    x[p12,p13],    x[p12,p23],
                        x[p13,p12],    x[p13,p13],    x[p13,p23],        
                        x[p23,p12],    x[p23,p13],    x[p23,p23]] );
        
        mat2 := Matrix( GF( q ), 3, 3, [
                        x[p13,p13],    x[p13,p14],    x[p13,p34],
                        x[p14,p13],    x[p14,p14],    x[p14,p34],        
                        x[p34,p13],    x[p34,p14],    x[p34,p34]] );
        
        if Determinant( mat1 ) eq 0 or Determinant( mat2 ) eq 0 then 
            continue;
        else
            mm1 := __funcAltSquareToSLdq( mat1 ); 
            mm2 := __funcAltSquareToSLdq( mat2 );
            if mm1[1,1] ne 0 and mm1[1,3] ne 0 then break; end if;
        end if;
                        
    end while;

    assert mm1[1,1] eq mm2[1,1];
    
    lambdasq := mm1[1,3]/mm2[1,2]; 
    is_sq, lambda := IsSquare( lambdasq );
    
    if is_sq then 
      for i in [1..dH], j in [dH+1..dim] do
            pij := funcpos_altsquare( dim, i, j ); 
            bas_mat[pij] *:= lambda;
       end for; 
    else 
      z0 := PrimitiveElement( GF( q ));
      lambda := Sqrt( z0*lambdasq );
      for i in [1..dH], j in [dH+1..dim] do
            pij := funcpos_altsquare( dim, i, j ); 
            bas_mat[pij] *:= lambda;
      end for;
    
      for i in [dH+1..dim], j in [i+1..dim] do
            pij := funcpos_altsquare( dim, i, j );
            bas_mat[pij] *:= z0;
      end for;
    end if; 

    return bas_mat;
end function;

/* 
   find the right basis transformation matrix

   This functions puts together the right transformation matrix from the bases of the components 
   H, K, T, and the one-dimensional component. 
*/

find_scalars_for_exterior_square_sp := function( G, bas_mat, basH, basK, basT, basOneDim )

    // set up some variables
    dH := SolveAltSquareDimEq( #basH : type := "Sp" );
    dK := SolveAltSquareDimEq( #basK : type := "Sp" );
    q := #CoefficientRing( G ); dim := dH + dK;
    dimg := Dimension( G );
    _, p := IsPrimePower( q );
    pdividesd := dim mod p eq 0;
    z := PrimitiveElement( GF( q ));

    // g preserves a bilinear form
    form := bas_mat*ClassicalForms( G )`bilinearForm*Transpose( bas_mat );
    if not IsSquare( form[1,dimg] ) then form *:= z; end if;
    
    // here we sample the values of the form to determine the right scalars

    // calculate the entry in the Gram matrix that corresponds to 
    // <f1f{d+1},e1e{d+1}>
    posT := funcpos_altsquare( dim, dim, dim-dH div 2 : type := "Sp" );
    if pdividesd then posT -:= 1; end if;  
    value_T := form[dH div 2,posT];
    
    // calculate the entry that corresponds to <e1e2,f2f1>
    value_H := Sqrt( form[1,dimg] )^-1;

    // calculate the entry in the Gram matrix that corresponds to 
    // <e{d+1}e{d+2},f{d+2}f{d+1}>
    posK1 := funcpos_altsquare( dim, dH div 2+1, dH div 2+2 : type := "Sp" );
    posK2 := funcpos_altsquare( dim, dim-dH div 2-1, dim-dH div 2 : type := "Sp" );
    if pdividesd then posK2 -:= 1; end if; 
    value_K := Sqrt( form[posK1,posK2] )^-1;

    // if p does not devide dim, then we need to deal with the 
    // scalar of the one-dimensional component Z
    if not pdividesd then
       vect := (BuildBasisMatrixSp( GF( q ), dH, dK )^-1)[dimg];
       posV := funcpos_altsquare( dim, dH div 2 + 1, dim div 2 + dK div 2  : type := "Sp" );
       b0_st := -vect[dim-1]^2*(dH div 2) - vect[posV]^2*(dK div 2); 
       b0 := (vect*form*Transpose( Matrix( vect )))[1];
       value_Z := Sqrt( b0_st/b0 );
       basOneDim[1] *:= value_Z; 

       // this is an alternative for getting value_Z
       // in fact this might be cheaper

       // get the (e1f1-enfn,e1f1-enfn)-entry of the Gram matrix 
       // b := form[dim-1,dim-1];
       // dH2 := dH div 2; dK2 := dK div 2;
       // value_Z := Sqrt(((-b-2)/((dH div 2)^-1+(dK div 2)^-1)+1))^-1;
    end if; 

    // in the form that is preserved the value of <e1*e{d+1},f1*f{d+1}> must be a squaree
    if not IsSquare( value_T ) then 
        // if not square, we modify the basis of H. we simulate the multplication of 
        // the basis element e_i for i in {1...d} by the primitive element z.
        for i in [1..#basH] do 
            pos := funcposinv_altsquare( dH, i : type := "Sp" );
            // multiply things of the form ei*ej by z^2 
            if pos[1] le dH div 2 and pos[2] le dH div 2 then
                basH[i] *:= z^2;
            // multiply things of the form ei*fj by z
            elif pos[1] le dH div 2 and pos[2] gt dH div 2 then
                basH[i] *:= z;
           end if;
        end for;

        // we also multiply elements of basT by z 
        for i in [1..#basT/2] do 
            basT[i] *:= z;
        end for;
        value_H *:= z^-1;
        value_T := Sqrt( z*value_T )^-1;
    else 
        value_T := Sqrt( value_T )^-1;
    end if;    

   
   // modyfy basis elements so that the Gram matrix is contains ones
   for i in [1..#basH] do 
       basH[i] *:= value_H;
   end for;
   
   for i in [1..#basK] do
       basK[i] *:= value_K;
   end for;

       
   for i in [1..#basT] do
       basT[i] *:= value_T;
   end for;

   // determine the final coefficients
   v, coeffs := TestBasisSp( basH, basK, basT, basOneDim, G );  assert v; 
   return BuildBasisMatrixSp( GF(q), dH, dK : scalars := coeffs )*Matrix( basH cat basK cat basT cat basOneDim );
end function;

